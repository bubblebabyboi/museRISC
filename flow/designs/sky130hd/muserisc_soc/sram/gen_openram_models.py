#!/usr/bin/env python3
"""Write 2-state behavioural models of the ORFS sky130 OpenRAM macros.

The vendor models (flow/platforms/sky130ram/<macro>/<macro>.v in the
ORFS image) print on every access, use #DELAY and X, and set dout with
a blocking assignment on the rising edge, which races a capture flop
on the same edge in a zero-delay simulator. These models keep the
vendor port timing for Verilator:

  * all inputs are registered on the rising clock edge;
  * after every rising edge dout0/dout1 are undefined (X in the vendor
    model; pseudo-random garbage here, since a 2-state simulator would
    turn X into 0 and could hide a missing capture register);
  * on the falling edge port 0 writes the array under the byte mask,
    and a selected read port loads dout from the array. dout is valid
    only from the falling edge to the next rising edge, matching the
    .lib falling_edge dout arcs;
  * a port-1 read of the address port 0 writes in the same cycle is
    unsupported by OpenRAM (the vendor model prints a WARNING), so it
    returns whole-word garbage (assumes clk0 == clk1, as in every
    museRISC instance). The array write itself still completes.

ORFS synthesis blackboxes the macros through their .lib; these files
only give slang the port lists and drive `make -C sim srammacro`.

Usage: gen_openram_models.py OUTDIR
"""
import sys
from pathlib import Path

MACROS = [  # (name, data width, address width, write-mask lanes)
    ("sky130_sram_1rw1r_64x256_8", 64, 8, 8),
    ("sky130_sram_1rw1r_128x256_8", 128, 8, 16),
    ("sky130_sram_1rw1r_44x64_8", 44, 6, 6),
]


def lane(b, width):
    lo = b * 8
    hi = min(lo + 8, width) - 1
    return f"[{hi}:{lo}]"


def model(name, w, aw, nm):
    writes = "\n".join(
        f"      if (wmask0_reg[{b}]) mem[addr0_reg]{lane(b, w)} <= din0_reg{lane(b, w)};"
        for b in range(nm))
    junk = f"{w}'({{{(w + 63) // 64}{{junk}}}})"
    return f"""// Generated by gen_openram_models.py: 2-state behavioural model of
// the OpenRAM macro {name} (see the script for the
// timing it reproduces). Each dout is single-driven: a tag toggled on
// the rising edge and copied on a falling-edge load marks it valid
// until the next rising edge.
module {name} (
    input  wire          clk0,
    input  wire          csb0,
    input  wire          web0,
    input  wire [{nm - 1}:0]    wmask0,
    input  wire [{aw - 1}:0]    addr0,
    input  wire [{w - 1}:0]   din0,
    output wire [{w - 1}:0]   dout0,
    input  wire          clk1,
    input  wire          csb1,
    input  wire [{aw - 1}:0]    addr1,
    output wire [{w - 1}:0]   dout1
);
  reg [{w - 1}:0] mem [0:{(1 << aw) - 1}];
  reg          csb0_reg, web0_reg, csb1_reg;
  reg [{nm - 1}:0]    wmask0_reg;
  reg [{aw - 1}:0]    addr0_reg, addr1_reg;
  reg [{w - 1}:0]   din0_reg, rd0_q, rd1_q;
  reg [63:0]   junk;
  reg          ptag0, ntag0, ptag1, ntag1;
  initial begin
    junk = 64'h9e3779b97f4a7c15;
    ptag0 = 1'b0;
    ntag0 = 1'b1;
    ptag1 = 1'b0;
    ntag1 = 1'b1;
  end

  always @(posedge clk0) begin
    csb0_reg   <= csb0;
    web0_reg   <= web0;
    wmask0_reg <= wmask0;
    addr0_reg  <= addr0;
    din0_reg   <= din0;
    junk       <= {{junk[62:0], junk[63] ^ junk[62] ^ junk[60] ^ junk[59]}};
    ptag0      <= ~ptag0;
  end
  always @(posedge clk1) begin
    csb1_reg  <= csb1;
    addr1_reg <= addr1;
    ptag1     <= ~ptag1;
  end

  // Port 0 write and read (falling edge).
  always @(negedge clk0) begin
    if (!csb0_reg && !web0_reg) begin
{writes}
    end
    if (!csb0_reg && web0_reg) begin
      rd0_q <= mem[addr0_reg];
      ntag0 <= ptag0;
    end
  end

  // Port 1 read (falling edge).
  always @(negedge clk1) begin
    if (!csb1_reg) begin
      // Same-address read during a port-0 write: unsupported,
      // whole-word garbage.
      if (!csb0_reg && !web0_reg && addr0_reg == addr1_reg)
        rd1_q <= ~{junk};
      else
        rd1_q <= mem[addr1_reg];
      ntag1 <= ptag1;
    end
  end

  assign dout0 = (ntag0 == ptag0) ? rd0_q : {junk};
  assign dout1 = (ntag1 == ptag1) ? rd1_q : ~{junk};
endmodule
"""


def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    for name, w, aw, nm in MACROS:
        (out / f"{name}.v").write_text(model(name, w, aw, nm))
        print(name)


if __name__ == "__main__":
    main()
