#!/bin/sh
# Regenerate the port-only stubs of the hard blocks used by the
# top-level synthesis of the hierarchical flow (../config.mk): each
# stub is the block module's header (parameters + ports) from the RTL
# with an empty body. Also writes strip_params.tcl, which removes the
# blocks' parameters from their instances after canonicalization
# (OpenSTA cannot read a parameterized instance of a liberty cell).
# Run from the repository root.
set -eu
d=flow/designs/sky130hd/sigil_hier/stubs
t=$d/strip_params.tcl
{
  echo "# GENERATED by $d/gen_stubs.sh (SYNTH_CANONICALIZE_TCL of ../config.mk):"
  echo "# drop the hard blocks' parameters from their instances."
} > $t
for spec in core/sigil_cpu.sv:sigil_cpu crypto/sigil_crypto_top.sv:sigil_crypto_top; do
  f=${spec%%:*}; m=${spec##*:}
  {
    echo "// GENERATED by $d/gen_stubs.sh from rtl/$f: port-only stub of"
    echo "// the $m hard block for the top-level synthesis. Do not edit."
    echo '`default_nettype none'
    awk -v m="$m" '$0 ~ "^module "m"[ ;(]" {p=1} p {print} p && /^\);/ {exit}' rtl/$f
    echo "endmodule"
    echo '`default_nettype wire'
  } > $d/${m}_stub.sv
  ps=$(sed -n '/^module /,/^) *(/p' $d/${m}_stub.sv | sed -n 's/.*parameter [^=]* \([A-Za-z_][A-Za-z0-9_]*\) *=.*/\1/p')
  if [ -n "$ps" ]; then
    echo "setparam$(for p in $ps; do printf ' -unset %s' $p; done) t:$m" >> $t
  fi
done
