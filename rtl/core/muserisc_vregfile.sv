// Vector register file (issue #23; element-serial rework).
// 32 registers of VLEN=512 bits stored as 256 words of 64
// bits (word address = {reg[4:0], word[2:0]}; element 0 is
// the lowest bits of word 0 of the first register).
//
// Storage is three identical 1R1W replicas of a 256x64 RAM
// with byte-write enables and a *synchronous* read (address
// sampled on the clock edge when re is high; the output
// register holds while re is low). One replica serves each
// read port (A = vs2/index, B = vs1, C = old vd/store data),
// and every write goes to all three. Each replica maps
// directly to a simple-dual-port BRAM (512x72 SDP) or a
// LUTRAM on FPGA, or a 1R1W byte-masked SRAM macro on ASIC
// (MUSERISC_SRAM_FAKERAM45 / MUSERISC_SRAM_SKY130 select the
// macro instance in the ORFS flows; default is behavioural).
//
// Read-during-write. SRAM macros leave a read of the word written in
// the same cycle undefined (OpenRAM documents same-address
// read+write as unsupported), so the replicas never see one:
//  * a read of the word being written by a FULL-word write (wbe=FF)
//    is not sent to the replica; the port returns the write data
//    instead (one-cycle full-word bypass, write-first semantics);
//  * a read colliding with a PARTIAL write is illegal and asserted
//    against in simulation. The vector unit avoids it by write
//    combining (most element writes are full-word) and by retrying
//    the read a cycle later otherwise (vrf_coll in muserisc_vec.sv);
//    the core's vector load/store sequencer never reads (RD phase)
//    and writes (ACC/WO phases) in the same cycle.
// A read in the cycle after a write sees the written data.
//
// Consumer contract: read data is valid the cycle after re
// and is then held while re stays low, but a held word does
// NOT reflect writes that land after it was sampled. A
// consumer may hold read data across a write only if that
// write cannot touch bytes it still uses (true for the
// vector unit's in-order element pipeline and the MEM
// sequencer's RD/ACC phases; see docs/CORE.md).
//
// v0 is additionally mirrored in a 512-bit shadow so the
// mask bit of any element is available without a read port.
`default_nettype none
module muserisc_vrf_bank (
    input  wire        clk_i,
    input  wire        re_i,
    input  wire [7:0]  raddr_i,
    output logic [63:0] rdata_o,
    input  wire        we_i,
    input  wire [7:0]  waddr_i,
    input  wire [7:0]  wbe_i,
    input  wire [63:0] wdata_i
);
`ifdef MUSERISC_SRAM_FAKERAM45
  `define MUSERISC_SRAM_MACRO
`elsif MUSERISC_SRAM_SKY130
  `define MUSERISC_SRAM_MACRO
`endif
`ifdef MUSERISC_SRAM_MACRO
  // SRAM macros do not hold their read data: OpenRAM drives dout1
  // to X on every rising edge and reloads it on the falling edge
  // only when the port is selected, and fakeram-style macros
  // return X when deselected. A capture register restores the
  // contract: rdata_o is the macro output in the cycle after a
  // read, and the captured copy until the next read.
  logic [63:0] ram_rd, hold_q;
  logic        re_q;
  always_ff @(posedge clk_i) begin
    re_q <= re_i;
    if (re_q) hold_q <= ram_rd;
  end
  assign rdata_o = re_q ? ram_rd : hold_q;
`endif
`ifdef MUSERISC_SRAM_FAKERAM45
  // ASIC (Nangate45 ORFS flow): 1R1W fakeram45 macro generated by
  // flow/designs/nangate45/muserisc_soc/sram/gen_fakeram45_1r1w.py
  // (bit write mask: each byte enable drives 8 mask bits).
  logic [63:0] wmask;
  for (genvar b = 0; b < 8; b++) begin : g_wmask
    assign wmask[b*8 +: 8] = {8{wbe_i[b]}};
  end
  fakeram45_256x64_1r1w u_ram (
      .clk        (clk_i),
      .we_in      (we_i),
      .wr_addr_in (waddr_i),
      .wd_in      (wdata_i),
      .w_mask_in  (wmask),
      .re_in      (re_i),
      .rd_addr_in (raddr_i),
      .rd_out     (ram_rd)
  );
`elsif MUSERISC_SRAM_SKY130
  // ASIC (sky130hd ORFS flow): OpenRAM sky130_sram_1rw1r_64x256_8
  // (256 x 64, byte write mask). Port 0 (RW) is used write-only,
  // port 1 (R) is the read port; both chip selects are active low.
  // Inputs are registered on the rising edge; the array writes and
  // dout1 updates on the falling edge, so the macro-to-flop paths
  // from dout1 get half a clock period (see docs/SOC_AREA.md).
  /* verilator lint_off UNUSEDSIGNAL */
  logic [63:0] unused_dout0;
  /* verilator lint_on UNUSEDSIGNAL */
  sky130_sram_1rw1r_64x256_8 u_ram (
      .clk0   (clk_i),
      .csb0   (~we_i),
      .web0   (1'b0),
      .wmask0 (wbe_i),
      .addr0  (waddr_i),
      .din0   (wdata_i),
      .dout0  (unused_dout0),
      .clk1   (clk_i),
      .csb1   (~re_i),
      .addr1  (raddr_i),
      .dout1  (ram_rd)
  );
`else
  // Behavioural model (simulation, FPGA inference, and ASIC flows
  // that build the RAM from flops).
  logic [63:0] mem_q [256];
  always_ff @(posedge clk_i) begin
    if (we_i) begin
      for (int b = 0; b < 8; b++) begin
        if (wbe_i[b]) mem_q[waddr_i][b*8 +: 8] <= wdata_i[b*8 +: 8];
      end
    end
    if (re_i) rdata_o <= mem_q[raddr_i];
  end
`endif
`undef MUSERISC_SRAM_MACRO
endmodule

module muserisc_vregfile (
    input  wire        clk_i,
    // rst is unnecessary: vector registers are uninitialized
    // architecturally (tests write before reading).

    input  wire        re_a_i,
    input  wire [7:0]  raddr_a_i,
    output logic [63:0] rdata_a_o,
    input  wire        re_b_i,
    input  wire [7:0]  raddr_b_i,
    output logic [63:0] rdata_b_o,
    input  wire        re_c_i,
    input  wire [7:0]  raddr_c_i,
    output logic [63:0] rdata_c_o,
    output logic [511:0] v0_o,      // mask register shadow

    input  wire        we_i,
    input  wire [7:0]  waddr_i,
    input  wire [7:0]  wbe_i,       // byte enables
    input  wire [63:0] wdata_i
);

  logic [2:0]  re;
  logic [7:0]  raddr [3];
  logic [63:0] ram_q [3];
  assign re = {re_c_i, re_b_i, re_a_i};
  assign raddr[0] = raddr_a_i;
  assign raddr[1] = raddr_b_i;
  assign raddr[2] = raddr_c_i;

  // Full-word bypass state per port: the read sampled a word that a
  // full-word write wrote in the same cycle; return that data and
  // keep returning it (hold) until the port's next read.
  logic [2:0]  coll, byp_q;
  logic [63:0] byp_data_q [3];

  for (genvar p = 0; p < 3; p++) begin : g_port
    assign coll[p] = re[p] && we_i && (waddr_i == raddr[p]);
    muserisc_vrf_bank u_bank (
        .clk_i   (clk_i),
        .re_i    (re[p] && !coll[p]),
        .raddr_i (raddr[p]),
        .rdata_o (ram_q[p]),
        .we_i    (we_i),
        .waddr_i (waddr_i),
        .wbe_i   (wbe_i),
        .wdata_i (wdata_i)
    );
    always_ff @(posedge clk_i) begin
      if (re[p]) begin
        byp_q[p] <= coll[p];
        byp_data_q[p] <= wdata_i;
      end
    end
`ifndef SYNTHESIS
    // A read colliding with a partial write would need the unwritten
    // bytes from the replica, which the SRAM macros cannot give.
    always_ff @(posedge clk_i) begin
      if (coll[p] && (wbe_i != 8'hff))
        $error("muserisc_vregfile: port %0d reads word %0d in the cycle a partial write (be %h) writes it",
               p, raddr[p], wbe_i);
    end
`endif
  end

  assign rdata_a_o = byp_q[0] ? byp_data_q[0] : ram_q[0];
  assign rdata_b_o = byp_q[1] ? byp_data_q[1] : ram_q[1];
  assign rdata_c_o = byp_q[2] ? byp_data_q[2] : ram_q[2];

  // v0 shadow (register 0 = words 0..7).
  logic [511:0] v0_q;
  always_ff @(posedge clk_i) begin
    if (we_i && (waddr_i[7:3] == 5'd0)) begin
      for (int b = 0; b < 8; b++) begin
        if (wbe_i[b]) v0_q[{waddr_i[2:0], 6'd0} + 9'(b * 8) +: 8] <=
            wdata_i[b*8 +: 8];
      end
    end
  end
  assign v0_o = v0_q;

endmodule
`default_nettype wire
