#!/usr/bin/env python3
"""Miter: pmp_check_par == pmp_check, from the functions in sigil_csr.sv.

  python3 gen_miter.py RTL_CORE_DIR OUT_DIR

Copies pmp_match, pmp_check and pmp_check_par verbatim out of
RTL_CORE_DIR/sigil_csr.sv into one module whose output ok is 1 iff the
parallel FPGA_TIMING check (#53) gives the serial check's verdict for
the given PMP state (16 x pmpcfg, 16 x pmpaddr[53:0]), address, access
type, privilege and width. Every input is free except that a wide
(8-byte) access has addr[2] = 0: the core issues 8-byte accesses only
8-byte aligned (a misaligned access traps before its PMP verdict is
used) and the walker port's PTE reads/writes are 8-byte aligned.

Also writes mutants that the proof must reject:
  mut1  pmp_check_par: a split match (one word of an 8-byte access)
        no longer fails (drops "& ~part", the #78 rule)
  mut2  pmp_check_par: the second word's TOR lower bound ignores
        eqo (entry i-1's bound equal to the second word)
  mut3  pmp_check (the reference side): the split-match deny removed
"""
import re
import sys
from pathlib import Path

rtl, out = Path(sys.argv[1]), Path(sys.argv[2])
src = (rtl / "sigil_csr.sv").read_text()


def fn(name):
    m = re.search(r"  function automatic logic(?: \[1:0\])? " + name +
                  r"\(.*?\n  endfunction\n", src, re.S)
    assert m, name
    return m.group(0)


m = re.search(r"PRIV_M = (2'b[01]{2})", src)
assert m and m.group(1) == "2'b11", "PRIV_M"
assert re.search(r"logic \[7:0\]\s+pmpcfg_q \[0:15\];", src), "pmpcfg_q"
assert re.search(r"logic \[63:0\]\s+pmpaddr_q \[0:15\];", src), "pmpaddr_q"
body = fn("pmp_match") + fn("pmp_check") + fn("pmp_check_par")

HEAD = """// GENERATED by gen_miter.py from rtl/core/sigil_csr.sv (pmp_match,
// pmp_check, pmp_check_par copied verbatim@NOTE@): ok = 1 iff
// pmp_check_par == pmp_check for every PMP state, address, access,
// privilege and width (wide only with addr[2] = 0).
module pmp_csr_miter (
    input  logic [63:0]      addr,
    input  logic [1:0]       acc,
    input  logic [1:0]       priv,
    input  logic             wide,
    input  logic [16*8-1:0]  cfg_flat,
    input  logic [16*54-1:0] paddr_flat,
    output logic             ok,
    output logic             ser,
    output logic             par
);
  localparam logic [1:0] PRIV_M = 2'b11;
  logic [7:0]  pmpcfg_q  [0:15];
  logic [63:0] pmpaddr_q [0:15];
  always_comb for (int i = 0; i < 16; i++) begin
    pmpcfg_q[i]  = cfg_flat[i*8 +: 8];
    pmpaddr_q[i] = {10'd0, paddr_flat[i*54 +: 54]};
  end
"""
TAIL = """
  assign ser = pmp_check(addr, acc, priv, wide);
  assign par = pmp_check_par(addr, acc, priv, wide);
  assign ok = (wide && addr[2]) ? 1'b1 : (ser == par);
endmodule
"""

MUTANTS = {
    "mut1": ("|(first & perm & ~part);", "|(first & perm);"),
    "mut2": ("ge_prev_o[i] = !lt[i-1] || eqo[i-1];", "ge_prev_o[i] = !lt[i-1];"),
    "mut3": ("if (wide && (m[0] != m[1])) begin\n          allow = 1'b0;\n        end else if",
             "if (1'b0) begin\n          allow = 1'b0;\n        end else if"),
}

out.mkdir(parents=True, exist_ok=True)
(out / "pmp_csr_miter.sv").write_text(HEAD.replace("@NOTE@", "") + body + TAIL)
for name, (old, new) in MUTANTS.items():
    assert body.count(old) == 1, (name, body.count(old))
    note = f"; {name}: '{old.splitlines()[0].strip()}' changed"
    (out / f"pmp_csr_miter_{name}.sv").write_text(HEAD.replace("@NOTE@", note) + body.replace(old, new) + TAIL)
print("wrote", out / "pmp_csr_miter.sv", "and", ", ".join(MUTANTS))
