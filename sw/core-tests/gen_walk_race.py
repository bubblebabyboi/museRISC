#!/usr/bin/env python3
"""Generate the fetch-walk vs data-walk race tests (#53 review).

  gen_walk_race.py root1 > vm_walk_race_directed.S
  gen_walk_race.py root0 > vm_walk_overlap_directed.S

Each variant ends a 4K code page with SFENCE.VMA, a few NOPs and
loads/stores to data pages, so the fetch walk for the next code page
and the data walks of those accesses overlap with every relative
timing. The values loaded and stored are checked on the next page.
root1: data in another gigapage (root[1]) than the code (root[0]), so
a walker that applies one walk's PTE to the other walk goes wrong.
root0: data in the code's gigapage (root[0], L1[2]): the same races,
with a shared root PTE."""
import itertools, sys
MODE = sys.argv[1] if len(sys.argv) > 1 else "root1"

N_VARIANTS = []
for pre, post, kind in itertools.product(range(4), range(4), ("ld", "ld2", "sd", "ldsd")):
    N_VARIANTS.append((pre, post, kind))

out = []
w = out.append
DVA = "0x40000000" if MODE == "root1" else "0x00400000"
DESC = ("data lives in VA 0x40000000.. (root[1], a different root PTE than\n// the code) mapped to PA 0x1C0000..." if MODE == "root1" else
        "data lives in VA 0x400000.. (root[0] like the code, L1[2]) mapped\n// to PA 0x1C0000...")
w(("""// GENERATED by sw/core-tests/gen_walk_race.py """ + MODE + """ (#53 review): fetch
// walks racing data walks. Code runs in S from identity-mapped 4K
// pages (global); """ + DESC + """ Each variant ends a code page
// with SFENCE.VMA, `pre` NOPs, its data accesses and `post` NOPs, so
// the I-walk for the next page and the D-walks overlap at every
// relative timing (with random bus latency the port arbitration
// varies too). A walker that consumed one walk's PTE for the other
// translates the data access to a code page (wrong value) or faults.
// Exit store 0 = pass; else (first failing variant + 1) | (failures << 16),
// or (variant + 1) | (mcause << 16) on a trap.
    .option norvc
    .option norelax
    .text
    .globl _start
.equ PGROOT, 0x100000
.equ PGL1C,  0x101000      // code L1 (root[0])
.equ PGL0C,  0x102000      // code L0: identity 4K pages 0..2M
.equ PGL1D,  {PGL1D}      // data L1
.equ PGL0D,  0x104000      // data L0
.equ DVA,    {DVA}
.equ DPA,    0x1C0000
.equ EXIT,   0x10000000
.equ ROOTD_OFF, {ROOTD_OFF}
.equ L1D_OFF,   {L1D_OFF}
_start:
    la sp, stack_top
    la t1, handler_m
    csrw mtvec, t1
    li t1, -1
    csrw pmpaddr15, t1
    li t1, 0x1f
    slli t1, t1, 56
    csrw pmpcfg2, t1
    li t1, PGROOT
    li t2, PGROOT + 0x5000
1:  sd x0, 0(t1)
    addi t1, t1, 8
    blt t1, t2, 1b
    // root[0] -> code L1, root[1] -> data L1
    li t1, (PGL1C >> 2) | 1
    li t2, PGROOT
    sd t1, 0(t2)
    li t1, (PGL1D >> 2) | 1
    sd t1, ROOTD_OFF(t2)
    li t1, (PGL0C >> 2) | 1
    li t2, PGL1C
    sd t1, 0(t2)
    li t1, (EXIT >> 2) | 0xE7      // exit page: 2M leaf, global
    li t2, PGL1C + 128 * 8
    sd t1, 0(t2)
    li t1, (PGL0D >> 2) | 1
    li t2, PGL1D + L1D_OFF
    sd t1, 0(t2)
    // code L0: 512 identity 4K pages, V R W X G A D
    li t1, 0xEF
    li t2, PGL0C
    li a0, 512
1:  sd t1, 0(t2)
    li a1, (0x1000 >> 2)
    add t1, t1, a1
    addi t2, t2, 8
    addi a0, a0, -1
    bnez a0, 1b
    // data L0: 64 pages DVA+i*4K -> DPA+i*4K RW A D (non-global);
    // word 0 of page i = 0x5A000000 + i
    li t1, (DPA >> 2) | 0xC7
    li t2, PGL0D
    li a2, DPA
    li a3, 0x5A000000
    li a0, 64
1:  sd t1, 0(t2)
    sd a3, 0(a2)
    li a1, (0x1000 >> 2)
    add t1, t1, a1
    addi t2, t2, 8
    li a1, 0x1000
    add a2, a2, a1
    addi a3, a3, 1
    addi a0, a0, -1
    bnez a0, 1b
    li t1, (8 << 60) | (PGROOT >> 12)
    csrw satp, t1
    sfence.vma
    la t1, s_main
    csrw mepc, t1
    li t1, (3 << 11)
    csrc mstatus, t1
    li t1, (1 << 11)
    csrs mstatus, t1
    mret
s_main:
    // sanity: the data mapping without any race (t0 = 100)
    li t0, 100
    li s4, DVA + 5 * 0x1000
    ld a3, 0(s4)
    li a5, 0x5A000005
    la s9, final
    bne a3, a5, fail
    sfence.vma
    nop
    nop
    nop
    nop
    ld a3, 0(s4)
    bne a3, a5, fail
    li s10, 0
    li s11, 0
    j v0_start
pass:
    li t1, EXIT
    sd x0, 0(t1)
1:  j 1b
fail:                          // record and continue with the next variant
    bnez s10, 1f
    mv s10, t0
1:  addi s11, s11, 1
    jr s9
final:
    beqz s11, pass
    slli s11, s11, 16
    or t0, s10, s11
    li t1, EXIT
    sd t0, 0(t1)
1:  j 1b
handler_m:                     // any trap fails (cause in t0 high bits)
    csrr t1, mcause
    slli t1, t1, 16
    or t0, t0, t1
    li t1, EXIT
    sd t0, 0(t1)
1:  j 1b
    .p2align 12
v0_page:
""").replace("{DVA}", DVA).replace("{PGL1D}", "0x103000" if MODE == "root1" else "0x101000").replace("{ROOTD_OFF}", "8" if MODE == "root1" else "0").replace("{L1D_OFF}", "0" if MODE == "root1" else "16"))
# Data pages: variant v uses pages (2v) and (2v+1) mod 64.
def page(v, k):
    return (2 * v + k) % 64

for v, (pre, post, kind) in enumerate(N_VARIANTS):
    p0, p1 = page(v, 0), page(v, 1)
    acc = []
    if kind == "ld":
        acc = [f"ld a3, 0(s4)"]
    elif kind == "ld2":
        acc = [f"ld a3, 0(s4)", f"ld a4, 0(s5)"]
    elif kind == "sd":
        acc = [f"sd s8, 8(s4)"]
    else:
        acc = [f"ld a3, 0(s4)", f"sd s8, 8(s5)"]
    blk = ["sfence.vma"] + ["nop"] * pre + acc + ["nop"] * post
    nbytes = 4 * len(blk)
    w(f"""
v{v}_start:                       // set up variant {v} ({pre},{post},{kind})
    li t0, {v + 1}
    la s9, v{v}_next
    li s4, DVA + {p0} * 0x1000
    li s5, DVA + {p1} * 0x1000
    li s8, 0x77000000 + {v}
    li a3, 0
    li a4, 0
    j v{v}_blk
    .skip 4096 - {nbytes} - (. - v{v}_page), 0
v{v}_blk:""")
    for ins in blk:
        w(f"    {ins}")
    # next page: checks
    nxt = v + 1
    w(f"""v{nxt}_page:
v{v}_chk:                         // first instruction on the next page
    nop""")
    if kind in ("ld", "ld2", "ldsd"):
        w(f"    li a5, 0x5A000000 + {p0}\n    bne a3, a5, fail")
    if kind == "ld2":
        w(f"    li a5, 0x5A000000 + {p1}\n    bne a4, a5, fail")
    if kind == "sd":
        w(f"    ld a5, 8(s4)\n    bne a5, s8, fail")
    if kind == "ldsd":
        w(f"    ld a5, 8(s5)\n    bne a5, s8, fail")
    w(f"v{v}_next:\n    j {'final' if v + 1 == len(N_VARIANTS) else 'v%d_start' % (v + 1)}")

w("""
    .data
    .align 4
stack: .skip 1024
stack_top:
""")
sys.stdout.write("\n".join(out) + "\n")
