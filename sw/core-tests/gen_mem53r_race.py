#!/usr/bin/env python3
"""Generate mem53r_race_directed.S (#53 review round 3, memory lens).

  gen_mem53r_race.py > mem53r_race_directed.S

Like gen_walk_race.py (scalar ld/sd), but the accesses racing the fetch
walk of the next code page are vector loads/stores (unit-stride across
a page, strided over four pages, indexed over four pages, a segment
load across a page), AMOs, LR/SC, and stores (scalar and vector) that
need a D write-back. Each variant ends a 4K code page with SFENCE.VMA,
`pre` NOPs, the access and `post` NOPs, so the fetch walk of the next
page, the element/data walks, the A/D write-back under the walker lock
and (FPGA_TIMING) the registered-lookup replays overlap at every
relative timing; the results are checked on the next page."""
import itertools, sys

KINDS = ("vle", "vlse", "vlux", "vseg", "vse", "vsux", "amo", "lrsc", "sdD", "vseD")
VARIANTS = [(pre, post, kind) for kind, pre, post in
            itertools.product(KINDS, range(4), range(4))]
NV = len(VARIANTS)

out = []
w = out.append
w("""// GENERATED by gen_mem53r_race.py (#53 review round 3, memory lens):
// fetch walks racing vector element walks, AMO/LR/SC walks and A/D
// write-backs. Code runs in S from identity-mapped 4K pages (global);
// data lives in VA 0x400000.. (L1[2]) mapped to PA 0x1C0000..; every
// data dword initially holds its PA. Loads use pages 0..31 (never
// written), stores pages 32..63. Each variant ends a code page with
// SFENCE.VMA, `pre` NOPs, its access and `post` NOPs; the next page
// checks the result. Kinds: vle (unit-stride across a page), vlse
// (stride 4K, 4 pages), vlux (indexed, 4 pages, out of order), vseg
// (vlseg2e64 across a page), vse, vsux, amo (amoadd.d), lrsc, sdD
// (sd to a page whose PTE lost D), vseD (vse64 across two pages that
// lost D). Exit store 0 = pass; else (first failing variant + 1) |
// (failures << 16), or (variant + 1) | (mcause << 16) on a trap.
    .option arch, +v
    .option norvc
    .option norelax
    .text
    .globl _start
.equ PGROOT, 0x100000
.equ PGL1,   0x101000
.equ PGL0C,  0x102000      // code L0: identity 4K pages 0..2M
.equ PGL0D,  0x104000      // data L0
.equ DVA,    0x00400000
.equ DPA,    0x1C0000
.equ EXIT,   0x10000000
_start:
    la sp, stack_top
    la t1, handler_m
    csrw mtvec, t1
    li t1, (1 << 9)
    csrs mstatus, t1
    li t1, -1
    csrw pmpaddr15, t1
    li t1, 0x1f
    slli t1, t1, 56
    csrw pmpcfg2, t1
    li t1, PGROOT
    li t2, PGROOT + 0x5000
1:  sd x0, 0(t1)
    addi t1, t1, 8
    blt t1, t2, 1b
    li t1, (PGL1 >> 2) | 1
    li t2, PGROOT
    sd t1, 0(t2)
    li t1, (PGL0C >> 2) | 1
    li t2, PGL1
    sd t1, 0(t2)
    li t1, (PGL0D >> 2) | 1
    sd t1, 16(t2)
    li t1, (EXIT >> 2) | 0xE7      // exit page: 2M leaf, global
    li t2, PGL1 + 128 * 8
    sd t1, 0(t2)
    li t1, 0xEF                    // code L0: V R W X G A D
    li t2, PGL0C
    li a0, 512
1:  sd t1, 0(t2)
    li a1, (0x1000 >> 2)
    add t1, t1, a1
    addi t2, t2, 8
    addi a0, a0, -1
    bnez a0, 1b
    li t1, (DPA >> 2) | 0xC7       // data L0: 64 pages RW A D
    li t2, PGL0D
    li a0, 64
1:  sd t1, 0(t2)
    li a1, (0x1000 >> 2)
    add t1, t1, a1
    addi t2, t2, 8
    addi a0, a0, -1
    bnez a0, 1b
    li t1, DPA                     // every data dword holds its PA
    li t2, DPA + 64 * 0x1000
1:  sd t1, 0(t1)
    addi t1, t1, 8
    blt t1, t2, 1b
    li t1, (8 << 60) | (PGROOT >> 12)
    csrw satp, t1
    sfence.vma
    la t1, s_main
    csrw mepc, t1
    li t1, (3 << 11)
    csrc mstatus, t1
    li t1, (1 << 11)
    csrs mstatus, t1
    mret
s_main:
    li s10, 0
    li s11, 0
    j v0_start
pass:
    li t1, EXIT
    sd x0, 0(t1)
1:  j 1b
fail:                          // record and continue with the next variant
    bnez s10, 1f
    mv s10, t0
1:  addi s11, s11, 1
    jr s9
final:
    beqz s11, pass
    slli s11, s11, 16
    or t0, s10, s11
    li t1, EXIT
    sd t0, 0(t1)
1:  j 1b
handler_m:                     // any trap fails (cause in t0 high bits)
    csrr t1, mcause
    slli t1, t1, 16
    or t0, t0, t1
    li t1, EXIT
    sd t0, 0(t1)
1:  j 1b
    .p2align 12
v0_page:""")

def lpage(v):          # 4 consecutive load pages
    return (4 * v) % 28
def spage(v):          # 4 consecutive store pages
    return 32 + (4 * v) % 28
def pa(pg, off):
    return f"DPA + {pg} * 0x1000 + {off:#x}"

for v, (pre, post, kind) in enumerate(VARIANTS):
    lb, sb = lpage(v), spage(v)
    setup = [f"li t0, {v + 1}", f"la s9, v{v}_next", f"li s8, 0x77000000 + {v} * 16",
             "li a3, 0", "li a4, -1"]
    acc = []
    chk = []
    vl4 = "vsetivli x0, 4, e64, m1, ta, ma"
    if kind == "vle":
        setup += [vl4, f"li s4, DVA + {lb} * 0x1000 + 0xFF0", "vmv.v.i v8, 0"]
        acc = ["vle64.v v8, (s4)"]
        exp = [pa(lb, 0xFF0), pa(lb, 0xFF8), pa(lb + 1, 0), pa(lb + 1, 8)]
        chk = ("v8", exp)
    elif kind == "vlse":
        setup += [vl4, f"li s4, DVA + {lb} * 0x1000 + 0x100", "li s6, 0x1000", "vmv.v.i v8, 0"]
        acc = ["vlse64.v v8, (s4), s6"]
        exp = [pa(lb + k, 0x100) for k in range(4)]
        chk = ("v8", exp)
    elif kind == "vlux":
        setup += [vl4, "la t1, idx_l", "vle64.v v4, (t1)", f"li s4, DVA + {lb} * 0x1000", "vmv.v.i v8, 0"]
        acc = ["vluxei64.v v8, (s4), v4"]
        exp = [pa(lb + 3, 0x108), pa(lb, 0x110), pa(lb + 2, 0x118), pa(lb + 1, 0x120)]
        chk = ("v8", exp)
    elif kind == "vseg":
        setup += ["vsetivli x0, 2, e64, m1, ta, ma", f"li s4, DVA + {lb} * 0x1000 + 0xFF0",
                  "vmv.v.i v8, 0", "vmv.v.i v9, 0"]
        acc = ["vlseg2e64.v v8, (s4)"]
        chk = ("seg", [pa(lb, 0xFF0), pa(lb + 1, 0), pa(lb, 0xFF8), pa(lb + 1, 8)])
    elif kind in ("vse", "vseD"):
        setup += [vl4, f"li s4, DVA + {sb} * 0x1000 + 0xFF0", "vid.v v8", "vadd.vx v8, v8, s8"]
        if kind == "vseD":
            setup += [f"li t1, PGL0D + {sb} * 8", "ld t2, 0(t1)", "andi t2, t2, ~0x80", "sd t2, 0(t1)",
                      "ld t2, 8(t1)", "andi t2, t2, ~0x80", "sd t2, 8(t1)"]
        acc = ["vse64.v v8, (s4)"]
        chk = ("mem", [(pa(sb, 0xFF0), 0), (pa(sb, 0xFF8), 1), (pa(sb + 1, 0), 2), (pa(sb + 1, 8), 3)])
    elif kind == "vsux":
        setup += [vl4, "la t1, idx_s", "vle64.v v4, (t1)", f"li s4, DVA + {sb} * 0x1000",
                  "vid.v v8", "vadd.vx v8, v8, s8"]
        acc = ["vsuxei64.v v8, (s4), v4"]
        chk = ("mem", [(pa(sb + 3, 0x408), 0), (pa(sb, 0x410), 1), (pa(sb + 2, 0x418), 2), (pa(sb + 1, 0x420), 3)])
    elif kind == "amo":
        setup += [f"li s4, DVA + {sb} * 0x1000 + 0x200"]
        acc = ["amoadd.d a3, s8, (s4)"]
        chk = ("amo", pa(sb, 0x200))
    elif kind == "lrsc":
        setup += [f"li s4, DVA + {sb} * 0x1000 + 0x208"]
        acc = ["lr.d a3, (s4)", "sc.d a4, s8, (s4)"]
        chk = ("lrsc", pa(sb, 0x208))
    elif kind == "sdD":
        setup += [f"li s4, DVA + {sb} * 0x1000", f"li t1, PGL0D + {sb} * 8", "ld t2, 0(t1)",
                  "andi t2, t2, ~0x80", "sd t2, 0(t1)"]
        acc = ["sd s8, 0x300(s4)"]
        chk = ("mem", [(pa(sb, 0x300), 0)])
    blk = ["sfence.vma"] + ["nop"] * pre + acc + ["nop"] * post
    nbytes = 4 * len(blk)
    w(f"\nv{v}_start:                       // variant {v} ({pre},{post},{kind})")
    for ins in setup:
        w(f"    {ins}")
    w(f"    j v{v}_blk\n    .skip 4096 - {nbytes} - (. - v{v}_page), 0\nv{v}_blk:")
    for ins in blk:
        w(f"    {ins}")
    w(f"v{v + 1}_page:\nv{v}_chk:                         // first instruction on the next page\n    nop")
    typ = chk[0]
    if typ in ("v8", "seg"):
        w("    vsetivli x0, 4, e64, m1, ta, ma" if typ == "v8" else "    vsetivli x0, 2, e64, m1, ta, ma")
        w("    la t1, vchk\n    vse64.v v8, (t1)")
        if typ == "seg":
            w("    addi t1, t1, 16\n    vse64.v v9, (t1)")
        w("    la t1, vchk")
        for i, e in enumerate(chk[1]):
            w(f"    ld t2, {8 * i}(t1)\n    li t3, {e}\n    bne t2, t3, fail")
    elif typ == "mem":
        for addr, k in chk[1]:
            w(f"    li t1, {addr}\n    ld t2, 0(t1)\n    addi t3, s8, {k}\n    bne t2, t3, fail")
        if kind in ("sdD", "vseD"):
            pages = [sb] if kind == "sdD" else [sb, sb + 1]
            for pg in pages:
                w(f"    li t1, PGL0D + {pg} * 8\n    ld t2, 0(t1)\n    andi t2, t2, 0xC0\n"
                  f"    li t3, 0xC0\n    bne t2, t3, fail")
    elif typ == "amo":
        w(f"    li t1, {chk[1]}\n    ld t2, 0(t1)\n    add t3, a3, s8\n    bne t2, t3, fail")
    elif typ == "lrsc":
        w(f"    bnez a4, fail\n    li t1, {chk[1]}\n    ld t2, 0(t1)\n    bne t2, s8, fail")
    w(f"v{v}_next:\n    j {'final' if v + 1 == NV else 'v%d_start' % (v + 1)}")

w("""
    .data
    .align 3
idx_l: .quad 0x3108, 0x110, 0x2118, 0x1120
idx_s: .quad 0x3408, 0x410, 0x2418, 0x1420
vchk:  .skip 64
    .align 4
stack: .skip 1024
stack_top:
""")
sys.stdout.write("\n".join(out) + "\n")
