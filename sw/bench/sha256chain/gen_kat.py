#!/usr/bin/env python3
"""Expected results for the sha256chain benchmarks, from Python hashlib.

Run at build time by the benchmarks' Makefiles, so the answers always
match the iteration count the image is built for:

  gen_kat.py chain <hashes>   > sha256chain_kat_<hashes>.h
  gen_kat.py bulk  <kib>      > sha256chain_bulk_kat_<kib>.h

The inputs are defined exactly as in sha256_kat.c:
  seed(j)[k] = (k + 17 j) mod 256          (lane j; single chains use j = 0)
  message[i] = (x_i >> 16) & 0xff, x_i = x_{i-1} * 1103515245 + 12345
               mod 2^32, x_0 = 12345        (bulk buffer)
and the chain is h_{i+1} = H(h_i), h_0 = seed, over the whole digest.
"""

import hashlib
import sys

LANES = 16


def seed(lane, n):
    return bytes((k + 17 * lane) & 0xFF for k in range(n))


def chain(name, h, n):
    for _ in range(n):
        h = hashlib.new(name, h).digest()
    return h


def message(n):
    x, out = 12345, bytearray(n)
    for i in range(n):
        x = (x * 1103515245 + 12345) & 0xFFFFFFFF
        out[i] = (x >> 16) & 0xFF
    return bytes(out)


def carray(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{{body}}};"


def carray2(name, rows):
    inner = ",\n    ".join("{" + ", ".join(f"0x{b:02x}" for b in r) + "}" for r in rows)
    return f"static const uint8_t {name}[{len(rows)}][{len(rows[0])}] = {{\n    {inner}}};"


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in ("chain", "bulk"):
        sys.exit("usage: gen_kat.py chain <hashes> | bulk <kib>")
    mode, n = sys.argv[1], int(sys.argv[2])
    if n < 1:
        sys.exit("gen_kat.py: count must be >= 1")
    out = ["/* Generated by sw/bench/sha256chain/gen_kat.py (Python hashlib "
           f"{sys.version.split()[0]}); do not edit. */",
           "#include <stdint.h>"]
    if mode == "chain":
        lanes = [chain("sha256", seed(j, 32), n // LANES + (1 if j < n % LANES else 0))
                 for j in range(LANES)]
        out += [f"#define KAT_CHAIN_HASHES {n}",
                "/* h_n, h_0 = seed(0): SHA-256, SHA-512 (64-byte seed), SHA3-256 */",
                carray("kat_chain_sha256", chain("sha256", seed(0, 32), n)),
                carray("kat_chain_sha512", chain("sha512", seed(0, 64), n)),
                carray("kat_chain_sha3_256", chain("sha3_256", seed(0, 32), n)),
                f"/* RVV: lane j runs n/{LANES} (+1 for j < n%{LANES}) steps from seed(j) */",
                carray2("kat_chain_lanes", lanes)]
    else:
        buf = message(n * 1024)
        seg = len(buf) // LANES
        out += [f"#define KAT_BULK_KIB {n}",
                "/* digests of the whole buffer */",
                carray("kat_bulk_sha256", hashlib.sha256(buf).digest()),
                carray("kat_bulk_sha512", hashlib.sha512(buf).digest()),
                carray("kat_bulk_sha3_256", hashlib.sha3_256(buf).digest()),
                f"/* RVV: SHA-256 of each of the {LANES} equal segments */",
                carray2("kat_bulk_lanes",
                        [hashlib.sha256(buf[j * seg:(j + 1) * seg]).digest()
                         for j in range(LANES)])]
    print("\n".join(out))


if __name__ == "__main__":
    main()
