"""Known-answer vectors for the streaming hash engine (issue #6).

References:
  SHA-512, SHA3-256, SHAKE256  -> Python hashlib.
  Keccak-256 (original Keccak padding, as used by Ethereum) -> the
  in-repo sponge below over `golden.keccak_f1600`; hashlib has no
  Keccak-256 and pycryptodome is not a dependency. The sponge is
  validated against hashlib (same code with domain 0x06 / 0x1F must
  equal SHA3-256 / SHAKE256 on every vector) and against published
  Keccak-256 vectors.

  python3 sw/hash_kat.py --self-check        # references only
  python3 sw/hash_kat.py --header out.h      # C++ vectors for the TB
"""
import argparse
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from golden import keccak_f1600  # noqa: E402

RATE_SHA512 = 128
RATE_KECCAK = 136  # 1088-bit rate: SHA3-256, Keccak-256, SHAKE256

MODE_SHA512, MODE_SHA3_256, MODE_KECCAK256, MODE_SHAKE256 = 0, 1, 2, 3

# Published Keccak-256 vectors (Keccak team / Ethereum).
KECCAK256_KNOWN = {
    b"": "c5d2460186f7233c927e7db2dcc703c0"
         "e500b653ca82273b7bfad8045d85a470",
    b"abc": "4e03657aea45a94fc7d47ba826c8d667"
            "c0d1e6e33a64a036ec44f58fa12d6c45",
    b"The quick brown fox jumps over the lazy dog":
        "4d741b6f1eb29cb2a9b9911c82f56fa8"
        "d73b04959d3d9d222895df6c0b28aa15",
}


def sponge(msg, domain, outlen, rate=RATE_KECCAK):
    """Keccak[c=1600-8*rate] sponge with pad10*1 and a domain byte."""
    padded = bytearray(msg)
    padded.append(domain)
    padded += bytes((-len(padded)) % rate)
    padded[-1] |= 0x80
    st = [0] * 25
    for off in range(0, len(padded), rate):
        blk = padded[off:off + rate]
        for i in range(rate // 8):
            st[i] ^= int.from_bytes(blk[8 * i:8 * i + 8], "little")
        st = keccak_f1600(st)
    out = b""
    while True:
        out += b"".join(v.to_bytes(8, "little") for v in st)[:rate]
        if len(out) >= outlen:
            return out[:outlen]
        st = keccak_f1600(st)


def keccak256(msg):
    return sponge(msg, 0x01, 32)


def message(length, seed):
    """Deterministic, non-repeating-looking test bytes."""
    x = (seed * 0x9E3779B1 + 0x1234567) & 0xFFFFFFFF
    out = bytearray()
    for _ in range(length):
        x = (x * 1103515245 + 12345) & 0xFFFFFFFF
        out.append((x >> 16) & 0xFF)
    return bytes(out)


def lengths(rate):
    # 0, rate-1, rate, rate+1, multi-rate boundaries, word-tail cases.
    base = {0, 1, 2, 3, 4, 5, 7, rate - 1, rate, rate + 1,
            2 * rate - 1, 2 * rate, 2 * rate + 1, 3 * rate + 5, 1000}
    if rate == RATE_SHA512:
        # Length field (16 B) fits only if the 0x80 byte is <= byte 111.
        base |= {110, 111, 112, 113, 116, 124, 127,
                 rate + 111, rate + 112}
    else:
        base |= {132, 133, 134, 135}
    return sorted(base)


def vectors():
    vecs = []
    for n in lengths(RATE_SHA512):
        m = message(n, n)
        vecs.append(("sha512", MODE_SHA512, m, hashlib.sha512(m).digest()))
    for n in lengths(RATE_KECCAK):
        m = message(n, n + 7)
        vecs.append(("sha3_256", MODE_SHA3_256, m,
                      hashlib.sha3_256(m).digest()))
        vecs.append(("keccak256", MODE_KECCAK256, m, keccak256(m)))
    for m in (b"abc", b"The quick brown fox jumps over the lazy dog"):
        vecs.append(("sha512", MODE_SHA512, m, hashlib.sha512(m).digest()))
        vecs.append(("sha3_256", MODE_SHA3_256, m,
                     hashlib.sha3_256(m).digest()))
        vecs.append(("keccak256", MODE_KECCAK256, m, keccak256(m)))
    # SHAKE256: multi-block squeeze (output > rate needs >= 1 squeeze).
    for n, outlen in ((0, 32), (3, 136), (137, 137), (300, 300),
                      (272, 500)):
        m = message(n, n + 99)
        vecs.append(("shake256", MODE_SHAKE256, m,
                     hashlib.shake_256(m).digest(outlen)))
    return vecs


def self_check():
    for msg, want in KECCAK256_KNOWN.items():
        got = keccak256(msg).hex()
        assert got == want, (msg, got, want)
    for rate in (RATE_KECCAK,):
        for n in lengths(rate):
            m = message(n, n)
            assert sponge(m, 0x06, 32) == hashlib.sha3_256(m).digest(), n
            assert (sponge(m, 0x1F, 300) ==
                    hashlib.shake_256(m).digest(300)), n
    nvec = len(vectors())
    print(f"hash_kat.py: Keccak-256 sponge matches published vectors and "
          f"hashlib SHA3-256/SHAKE256; {nvec} stream vectors OK")


def c_bytes(data):
    if not data:
        return "{0}"
    return "{" + ",".join(f"0x{b:02x}" for b in data) + "}"


def write_header(path):
    vecs = vectors()
    lines = [
        "// Generated by sw/hash_kat.py -- do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "struct HashKat { const char* name; int mode; uint32_t len;",
        "  const uint8_t* msg; uint32_t outlen; const uint8_t* out; };",
    ]
    for i, (_, _, m, d) in enumerate(vecs):
        lines.append(f"static const uint8_t kMsg{i}[] = {c_bytes(m)};")
        lines.append(f"static const uint8_t kOut{i}[] = {c_bytes(d)};")
    lines.append("static const HashKat kHashKats[] = {")
    for i, (name, mode, m, d) in enumerate(vecs):
        lines.append(f'  {{"{name}", {mode}, {len(m)}u, kMsg{i}, '
                     f"{len(d)}u, kOut{i}}},")
    lines.append("};")
    lines.append(f"static const int kNumHashKats = {len(vecs)};")
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, path)
    print(f"hash_kat.py: wrote {len(vecs)} vectors to {path}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-check", action="store_true")
    ap.add_argument("--header")
    args = ap.parse_args()
    self_check()
    if args.header:
        write_header(args.header)
