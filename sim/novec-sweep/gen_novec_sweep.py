#!/usr/bin/env python3
"""Generate novec_sweep.S: an encoding sweep of the RVV encoding space
(OP-V, LOAD-FP/STORE-FP all widths/mop/mew/nf/lumop, vector CSR
neighbourhood) for differential comparison of Sigil's no-vector
configuration against Spike with V removed from --isa.

Per case the signature records (mcause or -1, mtval or -1, f8 bits).
The scalar-FP buffer the legal flw/fld/fsw/fsd touch is part of the
signature too. Run on core_tb (ELF mode, CORE_TB_SIGDUMP=1) and on
Spike (+signature=... --signature-granularity=8) and diff.
--mode m|s|u|vs|vu: privilege the sweep runs in. m: traps to M.
s/u: illegal-instruction delegated to HS (medeleg[2]), recorded from
scause/stval. vs: not delegated, recorded in M (mcause/mtval, cause 2
not virtual-instruction). vu: delegated through medeleg[2] and
hedeleg[2] to the VS handler (vscause/vstval via scause/stval).
Usage: gen_novec_sweep.py [--seed N] [--quick] [--mode M] [--shift2] [--list cases.txt] > novec_sweep.S
"""
import random, sys

seed = 1
quick = '--quick' in sys.argv
mode = sys.argv[sys.argv.index('--mode') + 1] if '--mode' in sys.argv else 'm'
assert mode in ('m', 's', 'u', 'vs', 'vu')
# --shift2: put every swept encoding at PC % 4 == 2 (one leading
# c.nop), so a share of them straddle I$ lines / fetch words.
shift2 = '--shift2' in sys.argv
if '--seed' in sys.argv:
    seed = int(sys.argv[sys.argv.index('--seed') + 1])
rng = random.Random(seed)
cases = []  # (encoding, comment)

def add(enc, c=''):
    cases.append((enc & 0xffffffff, c))

# A. OP-V: every funct3 x funct6 x vm, fixed registers.
for f3 in range(8):
    for f6 in range(64):
        for vm in range(2):
            add(f6 << 26 | vm << 25 | 2 << 20 | 11 << 15 | f3 << 12 | 1 << 7 | 0x57,
                f'opv f3={f3} f6={f6} vm={vm}')
# A2. OP-V random register fields (rd kept off s-regs/t-regs used
# by the harness: only x1/x13-x17/x28.. avoided by restricting rd).
for _ in range(300 if quick else 2000):
    hi = rng.getrandbits(25)
    rd = rng.choice([1, 13, 14, 15, 16, 17])
    hi = (hi & ~0x1f) | rd
    add(hi << 7 | 0x57, 'opv rand')
# B/C. LOAD-FP / STORE-FP: every width x bits[31:25] x bits[24:20],
# rs1 = a0 (buffer centre), rd/vs3 field = 8 (f8 / v8; imm[2:0] = 0
# for the stores). Legal scalar widths keep imm 8-byte aligned.
hi_range = range(0, 128, 9) if quick else range(128)
for opc in (0x07, 0x27):
    for f3 in range(8):
        for hi7 in hi_range:
            for r2 in range(32):
                if opc == 0x07 and f3 in (2, 3) and (r2 & 7):
                    continue
                add(hi7 << 25 | r2 << 20 | 10 << 15 | f3 << 12 | 8 << 7 | opc,
                    f'{"ld" if opc == 7 else "st"}fp f3={f3} hi7={hi7:#x} r2={r2}')
# D. CSR neighbourhood: reads (csrrs a3, csr, x0) and writes
# (csrrw x0, csr, a1) of 0x000-0x01F and 0xC00-0xC3F.
csrs = (list(range(0x000, 0x020)) + list(range(0xC00, 0xC40)) if mode == 'm'
        else list(range(0x001, 0x010)) + list(range(0xC20, 0xC30)))
for csr in csrs:
    add(csr << 20 | 0 << 15 | 2 << 12 | 13 << 7 | 0x73, f'csrr {csr:#x}')
    if csr < 0xC00:
        add(csr << 20 | 11 << 15 | 1 << 12 | 0 << 7 | 0x73, f'csrw {csr:#x}')
    add(csr << 20 | 5 << 15 | 6 << 12 | 13 << 7 | 0x73, f'csrrsi {csr:#x},5')

n_fs_on = len(cases)
# E. FS = Off: a slice of B/C again (scalar FP must trap too).
fsoff = []
for opc in (0x07, 0x27):
    for f3 in range(8):
        for hi7 in (0, 1, 0x02, 0x10, 0x40, 0x41):
            for r2 in (0, 8, 11, 16):
                fsoff.append((hi7 << 25 | r2 << 20 | 10 << 15 | f3 << 12 | 8 << 7 | opc,
                              f'fsoff f3={f3} hi7={hi7:#x} r2={r2}'))
for f3 in range(8):
    fsoff.append((0 << 26 | 1 << 25 | 2 << 20 | 11 << 15 | f3 << 12 | 1 << 7 | 0x57,
                  f'fsoff opv f3={f3}'))

out = []
w = out.append
w('// Generated by gen_novec_sweep.py (seed %d%s, mode %s): %d cases + %d FS=Off.'
  % (seed, ', quick' if quick else '', mode, len(cases), len(fsoff)))
w('    .option norvc')
w('    .text\n    .globl _start\n_start:')
w('    la t0, trap\n    csrw mtvec, t0')
w('    li t0, (3 << 13) | (3 << 9)\n    csrc mstatus, t0')
w('    li t0, (1 << 13) | (3 << 9)\n    csrs mstatus, t0   // FS = Initial; VS write ignored')
w('    csrwi fcsr, 0')
# Distinct FP register patterns.
for i in range(32):
    w(f'    li t0, 0x{(0x3ff0000000000000 + i * 0x0001000100010001) & ((1 << 64) - 1):016x}')
    w(f'    fmv.d.x f{i}, t0')
w('    la a0, fpbuf + 2048\n    li a1, 0x55\n    li a2, 8')
w('    la s2, records')
if mode != 'm':
    # PMP: entry 0 NAPOT over everything, RWX; bare translation.
    w('    csrw pmpcfg0, zero\n    csrw pmpcfg2, zero\n    li t0, -1\n    csrw pmpaddr0, t0')
    w('    li t0, 0x1f\n    csrw pmpcfg0, t0\n    csrw satp, zero\n    csrw 0x680, zero\n    csrw 0x280, zero')
    w('    li t0, -1\n    csrw mcounteren, t0\n    csrw scounteren, t0\n    csrw 0x606, t0')
    w('    csrw medeleg, zero\n    csrw 0x602, zero')
    if mode in ('s', 'u'):
        w('    li t0, 4\n    csrw medeleg, t0\n    la t0, strap\n    csrw stvec, t0')
    if mode == 'vu':
        w('    li t0, 4\n    csrw medeleg, t0\n    csrw 0x602, t0\n    la t0, strap\n    csrw 0x205, t0')
    # vsstatus.FS = Initial (V=1 needs both FS fields on), VS write ignored.
    w('    li t0, (1 << 13) | (3 << 9)\n    csrs 0x200, t0')
    mpp = {'s': 1, 'u': 0, 'vs': 1, 'vu': 0}[mode]
    mpv = 1 if mode in ('vs', 'vu') else 0
    w('    li t0, (3 << 11) | (1 << 39)\n    csrc mstatus, t0')
    w(f'    li t0, ({mpp} << 11) | ({mpv} << 39)\n    csrs mstatus, t0')
    w('    la t0, 97f\n    csrw mepc, t0\n    mret\n97:')
if shift2:
    w('    .option rvc\n    c.nop\n    .option norvc')
def emit(enc, c):
    w(f'    li s5, -1\n    li s6, -1\n    .word 0x{enc:08x}  // {c}')
    w('    sd s5, 0(s2)\n    sd s6, 8(s2)\n    fmv.x.d t4, f8\n    sd t4, 16(s2)\n    addi s2, s2, 24')
for e, c in cases:
    emit(e, c)
if mode != 'm':
    w('    ecall   // back to M')
# Record mstatus FS/VS/SD and misa.
w('    csrr t0, mstatus\n    li t1, (1 << 63) | (3 << 13) | (3 << 9)\n    and t0, t0, t1\n    sd t0, 0(s2)')
w('    csrr t0, misa\n    sd t0, 8(s2)\n    csrr t0, fcsr\n    sd t0, 16(s2)\n    addi s2, s2, 24')
w('    li t0, 3 << 13\n    csrc mstatus, t0   // FS = Off')
for e, c in fsoff:
    w(f'    li s5, -1\n    li s6, -1\n    .word 0x{e:08x}  // {c}')
    w('    sd s5, 0(s2)\n    sd s6, 8(s2)\n    sd zero, 16(s2)\n    addi s2, s2, 24')
w('    csrr t0, mstatus\n    li t1, (1 << 63) | (3 << 13) | (3 << 9)\n    and t0, t0, t1\n    sd t0, 0(s2)')
w('    li t0, 1\n    la t1, tohost\n    sd t0, 0(t1)\n1:  j 1b')
w('    .align 2\ntrap:\n    csrr t6, mcause\n    addi t6, t6, -8\n    li t5, 3\n    bgtu t6, t5, 1f')
w('    li t5, 3 << 11\n    csrs mstatus, t5\n    li t5, 1 << 39\n    csrc mstatus, t5')
w('    csrr t6, mepc\n    addi t6, t6, 4\n    csrw mepc, t6\n    mret')
w('1:  csrr s5, mcause\n    csrr s6, mtval\n    csrr t6, mepc\n'
  '    addi t6, t6, 4\n    csrw mepc, t6\n    mret')
w('    .align 2\nstrap:\n    csrr s5, scause\n    addi s5, s5, 0x100  // tag: taken by the S/VS handler\n    csrr s6, stval\n    csrr t6, sepc\n'
  '    addi t6, t6, 4\n    csrw sepc, t6\n    sret')
w('    .data\n    .align 6\n    .globl begin_signature\nbegin_signature:')
w('fpbuf:')
for i in range(512):
    w(f'    .dword 0x{(0x0123456789abcdef * (i + 1)) & ((1 << 64) - 1):016x}')
w(f'records:\n    .space {24 * (len(cases) + len(fsoff) + 3)}')
w('    .align 6\n    .globl end_signature\nend_signature:')
w('    .align 6\n    .globl tohost\ntohost: .dword 0\n    .globl fromhost\nfromhost: .dword 0')
print('\n'.join(out))
# Case list for localisation.
with open(sys.argv[sys.argv.index('--list') + 1] if '--list' in sys.argv else '/dev/null', 'w') as f:
    for i, (e, c) in enumerate(cases + [(0, 'mstatus/misa/fcsr')] + fsoff + [(0, 'mstatus')]):
        f.write(f'{i} {e:08x} {c}\n')
