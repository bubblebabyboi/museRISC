#!/usr/bin/env python3
"""ACT4 DUT config for the no-vector core (SIGIL_NO_VECTOR, issue #13).

Derives sigil-core-novec from the canonical sw/act4-core/ config, so the
two never drift: the same core with V removed.
  - sigil-core-novec.yaml: name, no Zve*/Zvl* extensions, the vector
    parameters dropped (VSSTATUS_VS_EXISTS is one), mstatus.VS
    read-only zero (MSTATUS_VS_LEGAL_VALUES [0]);
  - sail.json: V support_level Disabled (misa.V = 0, no vector CSRs,
    every vector encoding illegal, VS read-only zero in Sail);
  - test_config.yaml: name and udb_config;
  - run_cmd.txt: build/sim/core_tb_novec;
  - link.ld, rvmodel_macros.h: unchanged copies.
Usage: act4_novec_config.py <src dir (sw/act4-core)> <dst dir>
"""
import os
import re
import shutil
import sys

# UDB parameters that belong to the vector extension (absent without V).
VEC_PARAMS = re.compile(
    r"^  (VLEN|ELEN|SEW_MIN|HW_MSTATUS_VS_DIRTY_UPDATE|VFREDUSUM_\w+|"
    r"FOLLOW_VTYPE_RESET_RECOMMENDATION|RVV_VL_\w+|"
    r"SUPPORT_FRACTIONAL_LMUL_BEYOND_REQUIRED|VILL_SET_ON_RESERVED_VTYPE|"
    r"RESERVED_VSET_\w+|VECTOR_\w+|LEGAL_VSTART|"
    r"IMPRECISE_VECTOR_TRAP_SETTABLE|MUTABLE_MISA_V|VSSTATUS_VS_EXISTS)\s*:")


def yaml_novec(text):
    out = []
    for line in text.splitlines():
        if re.match(r"^\s*- \{ name: Zv[el]\w*,", line):
            continue
        if VEC_PARAMS.match(line):
            continue
        if line.startswith("name: sigil-core"):
            line = "name: sigil-core-novec"
        elif line.startswith("description:"):
            line = ("description: Sigil in-house RV64 core without the vector "
                    "unit (SIGIL_NO_VECTOR, issue #13) in the C++ Verilator harness")
        elif re.match(r"^  MSTATUS_VS_LEGAL_VALUES:", line):
            line = ("  # No vector unit: mstatus.VS is read-only zero "
                    "(sigil_csr.sv, HAS_VECTOR = 0).\n"
                    "  MSTATUS_VS_LEGAL_VALUES: [0]")
        out.append(line)
    return ("# Generated by scripts/act4_novec_config.py from "
            "sw/act4-core/sigil-core.yaml\n# (no-vector core, issue #13); "
            "edit the source and the script, not this file.\n"
            + "\n".join(out) + "\n")


def sail_novec(text):
    new, n = re.subn(r'("V"\s*:\s*\{[^{}]*?"support_level"\s*:\s*)"[A-Za-z_]+"',
                     r'\1"Disabled"', text, flags=re.S)
    if n != 1:
        sys.exit("sail.json: V support_level not found exactly once")
    return new


def main():
    src, dst = sys.argv[1], sys.argv[2]
    os.makedirs(dst, exist_ok=True)
    with open(os.path.join(src, "sigil-core.yaml")) as f:
        y = yaml_novec(f.read())
    code = "\n".join(l.split("#")[0] for l in y.splitlines())
    for leftover in ("name: Zv", "VLEN:", "ELEN:"):
        if leftover in code:
            sys.exit(f"sigil-core-novec.yaml still has {leftover}")
    with open(os.path.join(dst, "sigil-core-novec.yaml"), "w") as f:
        f.write(y)
    with open(os.path.join(src, "sail.json")) as f:
        s = sail_novec(f.read())
    with open(os.path.join(dst, "sail.json"), "w") as f:
        f.write(s)
    with open(os.path.join(src, "test_config.yaml")) as f:
        t = f.read()
    t = re.sub(r"^name: .*$", "name: sigil-core-novec", t, flags=re.M)
    t = re.sub(r"^udb_config: .*$", "udb_config: sigil-core-novec.yaml", t, flags=re.M)
    with open(os.path.join(dst, "test_config.yaml"), "w") as f:
        f.write(t)
    with open(os.path.join(dst, "run_cmd.txt"), "w") as f:
        f.write("build/sim/core_tb_novec\n")
    for n in ("link.ld", "rvmodel_macros.h"):
        shutil.copy(os.path.join(src, n), os.path.join(dst, n))
    print(f"no-vector ACT config written to {dst}")


if __name__ == "__main__":
    main()
