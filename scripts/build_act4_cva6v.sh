#!/usr/bin/env bash
# Generate ACT4 (riscv-arch-test) self-checking ELFs for the Sigil
# CVA6+Ara DUT config in sw/act4-cva6v/ (issue #9). Generation only:
# ELFs land in third_party/riscv-arch-test/work/sigil-cv64a6v/elfs/
# and are staged flat into third_party/ara/act-elfs/ for the chunked
# runner sw/act4-cva6v/run_actv.sh inside scripts/ara_docker.sh. The
# Sail reference model supplies expected results at generation time;
# each ELF is self-checking and reports via the Ara control-register
# halt (see sw/act4-cva6v/rvmodel_macros.h).
set -euo pipefail
cd "$(dirname "$0")/.."
ACT=third_party/riscv-arch-test
[ -d "$ACT/framework" ] || { echo "fetch riscv-arch-test first: ./scripts/setup.sh --fetch-act"; exit 1; }
command -v mise >/dev/null || { echo "install mise (https://mise.jdx.dev)"; exit 1; }
[ -x third_party/sail/bin/sail_riscv_sim ] || { echo "install Sail 0.15 into third_party/sail"; exit 1; }
if command -v riscv64-unknown-elf-gcc >/dev/null; then
  toolchain_prefix=riscv64-unknown-elf-
elif command -v riscv64-elf-gcc >/dev/null; then
  toolchain_prefix=riscv64-elf-
else
  echo "install a RISC-V bare-metal GCC (riscv64-unknown-elf- or riscv64-elf-)" >&2; exit 1
fi

# ACT configs expect riscv64-unknown-elf-* names (same aliasing as
# scripts/build_act4_cva6.sh).
mkdir -p build/riscv-alias/bin
for t in gcc g++ objdump objcopy nm ar as ld readelf size strip ranlib; do
  src="$(command -v "${toolchain_prefix}$t" || true)"
  if [ -n "$src" ]; then
    ln -sf "$src" "build/riscv-alias/bin/riscv64-unknown-elf-$t"
  fi
done
[ -x build/riscv-alias/bin/riscv64-unknown-elf-gcc ] || { echo "RISC-V GCC alias failed" >&2; exit 1; }
ln -sf "$PWD/third_party/sail/bin/sail_riscv_sim" build/riscv-alias/bin/sail_riscv_sim

if [ "$(uname -s)" = Darwin ] && [ -f /opt/homebrew/lib/libz3.dylib ]; then
  D="$HOME/.cache/udb/z3/z3-5.1.0/arm64"; mkdir -p "$D"
  for n in libz3.so libz3.so.4.8 libz3 z3 libz3.dylib; do
    [ -f "$D/$n" ] || cp /opt/homebrew/lib/libz3.dylib "$D/$n"
  done
fi

# Canonical config lives in sw/act4-cva6v/ (committed); the framework
# discovers configs under config/, so sync a copy into the
# (uncommitted) third_party tree on every run.
DST="$ACT/config/cores/sigil-cv64a6v"
mkdir -p "$DST"
cp sw/act4-cva6v/sigil-cv64a6v.yaml sw/act4-cva6v/sail.json \
   sw/act4-cva6v/link.ld sw/act4-cva6v/rvmodel_macros.h \
   sw/act4-cva6v/test_config.yaml sw/act4-cva6v/run_cmd.txt "$DST/"
echo "Synced DUT config to $DST"

cd "$ACT"
mise trust >/dev/null 2>&1 || true
# Generate test sources first (the elfs target's `tests` dependency is
# stamp-guarded and the stamps do not depend on EXTENSIONS, so drop
# them to force regeneration when the filter changes; scalar suites in
# this tree were generated by the B2 flow with a scalar filter). The
# unpriv vector suites expand by SEW in testgen's testplans reader:
# Vx/Vls -> 8,16,32,64 and Vf -> 16,32,64 (there is no plain "V").
# Vf16 requires Zvfhmin, which this DUT does not implement (see
# sigil-cv64a6v.yaml); generating it is harmless because ELF
# selection filters by the DUT's declared extensions.
VEXT="${EXTENSIONS:-Vx8,Vx16,Vx32,Vx64,Vls8,Vls16,Vls32,Vls64,Vf16,Vf32,Vf64}"
rm -f work/stamps/testgen.stamp work/stamps/vector-testgen-unpriv.stamp
PATH="$PWD/../../build/riscv-alias/bin:$PATH" \
  mise exec -- make tests vector-tests \
  EXTENSIONS="$VEXT"
# Invoke act directly (same arguments as the Makefile elfs recipe)
# with --keep-going: at arch-test 6af53584 one generated test
# (Vls16-vloxei32.v-00) overflows its trap signature on the Sail side
# ("Increase TRAP_SIGUPD_COUNT for this test"), which is a test-side
# defect independent of the DUT; without -k that single failure blocks
# promotion of every other ELF. The failure is recorded in the
# evidence, and this step still fails overall if nothing was built.
act_rc=0
PATH="$PWD/../../build/riscv-alias/bin:$PATH" \
  mise exec -- uv run act \
  config/cores/sigil-cv64a6v/test_config.yaml \
  --workdir work --test-dir tests --jobs 0 \
  --extensions "$VEXT" --exclude SdtrigSm,SdtrigS,SdtrigU \
  --fast --keep-going || act_rc=$?
echo "act exit code: $act_rc (nonzero is expected while the upstream test defect above persists)"
echo "ELFs: $ACT/work/sigil-cv64a6v/elfs/"
cd - >/dev/null

# Stage flat copies where the Ara Docker runner can see them through
# its /repo mount: third_party/ara/act-elfs/.
mkdir -p third_party/ara/act-elfs
src_count=0
find "$ACT/work/sigil-cv64a6v/elfs" -type f -name '*.elf' | sort | while read -r f; do
  b="$(basename "$f" .elf)"
  cp "$f" "third_party/ara/act-elfs/$b"
done
src_count="$(find "$ACT/work/sigil-cv64a6v/elfs" -type f -name '*.elf' | wc -l | tr -d ' ')"
staged_count="$(ls third_party/ara/act-elfs | wc -l | tr -d ' ')"
echo "Staged: $staged_count ELFs in third_party/ara/act-elfs/ (source: $src_count)"
[ "$staged_count" -gt 0 ] || { echo "no ELFs staged" >&2; exit 1; }
[ "$staged_count" -eq "$src_count" ] || { echo "basename collisions in staging ($staged_count != $src_count)" >&2; exit 1; }
